using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Xml.Linq;

namespace OpenIDEA.Editor
{
    internal static class OpenIDEAProjectGeneration
    {
        private const string ProjectTypeGuid = "9A19103F-16F7-4668-BE54-9A1E7A4F7556";
        private static readonly UTF8Encoding Utf8 = new UTF8Encoding(false);

        internal static ProjectGenerationResult Generate(string root, ProjectGenerationSources sources)
        {
            return Write(root, UnityProjectSnapshot.Collect(root, sources));
        }

        internal static ProjectGenerationResult Write(string root, ProjectAssembly[] assemblies)
        {
            root = Path.GetFullPath(root);
            var all = assemblies.ToDictionary(a => a.Name, StringComparer.Ordinal);
            var selected = assemblies.Where(a => a.GenerateProject && a.Sources.Count != 0).OrderBy(a => a.Name, StringComparer.Ordinal).ToArray();
            var names = new HashSet<string>(selected.Select(a => a.Name), StringComparer.Ordinal);
            var files = new List<KeyValuePair<string, string>>();
            foreach (var assembly in selected)
            {
                ValidateName(assembly.Name);
                files.Add(new KeyValuePair<string, string>(Path.Combine(root, assembly.Name + ".csproj"), ProjectText(assembly, all, names)));
            }
            var solution = Path.Combine(root, new DirectoryInfo(root).Name + ".sln");
            files.Add(new KeyValuePair<string, string>(solution, SolutionText(selected)));

            // Render the complete graph before replacing any file; publish the solution last.
            var changed = 0;
            foreach (var file in files)
                if (WriteIfChanged(file.Key, file.Value)) changed++;
            return new ProjectGenerationResult(solution, selected.Length, changed, files.Select(file => file.Key).ToArray());
        }

        private static string ProjectText(ProjectAssembly assembly, Dictionary<string, ProjectAssembly> all, HashSet<string> selected)
        {
            var project = new XElement("Project", new XAttribute("ToolsVersion", "Current"),
                new XComment(" Generated by OpenIDEA Editor for Unity. Regenerate from Preferences > External Tools. "),
                new XElement("PropertyGroup",
                    new XElement("BaseIntermediateOutputPath", "Temp/OpenIDEA/obj/" + MsBuildLiteral(assembly.Name) + "/")),
                new XElement("Import", new XAttribute("Project", "Sdk.props"), new XAttribute("Sdk", "Microsoft.NET.Sdk")));
            var properties = new XElement("PropertyGroup",
                new XElement("TargetFramework", "netstandard2.1"),
                new XElement("OutputType", "Library"),
                new XElement("AssemblyName", assembly.Name),
                new XElement("RootNamespace", assembly.RootNamespace ?? string.Empty),
                new XElement("LangVersion", assembly.LanguageVersion),
                new XElement("Configurations", "Debug;Release"),
                new XElement("IntermediateOutputPath", "$(BaseIntermediateOutputPath)$(Configuration)/"),
                new XElement("EnableDefaultItems", "false"),
                new XElement("GenerateAssemblyInfo", "false"),
                new XElement("GenerateTargetFrameworkAttribute", "false"),
                new XElement("ImplicitUsings", "disable"),
                new XElement("EnableNETAnalyzers", "false"),
                new XElement("NoStdLib", "true"),
                new XElement("NoConfig", "true"),
                new XElement("DisableImplicitFrameworkReferences", "true"),
                new XElement("AppendTargetFrameworkToOutputPath", "false"),
                new XElement("OutputPath", "Temp/OpenIDEA/bin/$(Configuration)/" + MsBuildLiteral(assembly.Name) + "/"),
                new XElement("DefineConstants", string.Join(";", Sorted(assembly.Defines))),
                new XElement("AllowUnsafeBlocks", assembly.AllowUnsafe ? "true" : "false"),
                new XElement("Optimize", assembly.Optimize ? "true" : "false"),
                new XElement("DebugType", "portable"));
            AddProperty(properties, "Nullable", assembly.Nullable);
            AddProperty(properties, "CheckForOverflowUnderflow", assembly.CheckOverflow);
            AddProperty(properties, "WarningLevel", assembly.WarningLevel);
            AddProperty(properties, "TreatWarningsAsErrors", assembly.TreatWarningsAsErrors);
            AddProperty(properties, "NoWarn", string.Join(";", Sorted(assembly.NoWarn)));
            AddProperty(properties, "WarningsAsErrors", string.Join(";", Sorted(assembly.WarningsAsErrors)));
            AddProperty(properties, "WarningsNotAsErrors", string.Join(";", Sorted(assembly.WarningsNotAsErrors)));
            AddProperty(properties, "CodeAnalysisRuleSet", assembly.Ruleset == null ? null : MsBuildLiteral(assembly.Ruleset));
            project.Add(properties);
            AddItems(project, "Compile", assembly.Sources);

            var binaries = new List<ProjectBinaryReference>(assembly.BinaryReferences);
            var projectReferences = new List<string>();
            foreach (var name in Sorted(assembly.AssemblyReferences))
            {
                if (!all.TryGetValue(name, out var dependency))
                    throw new InvalidDataException("Missing compilation data for " + assembly.Name + " -> " + name);
                if (selected.Contains(name)) projectReferences.Add(name + ".csproj");
                else binaries.Add(new ProjectBinaryReference(dependency.OutputPath));
            }
            AddItems(project, "ProjectReference", projectReferences);
            var references = new XElement("ItemGroup");
            var pathComparer = Path.DirectorySeparatorChar == '\\' ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;
            foreach (var group in binaries.GroupBy(r => r.Path, pathComparer).OrderBy(g => g.Key, StringComparer.Ordinal))
            {
                var reference = new XElement("Reference", new XAttribute("Include", MsBuildLiteral(Path.GetFileNameWithoutExtension(group.Key))),
                    new XElement("HintPath", MsBuildLiteral(group.Key)), new XElement("Private", "false"));
                var aliases = Sorted(group.SelectMany(r => r.Aliases.Split(','))).ToArray();
                if (aliases.Length != 1 || aliases[0] != "global") reference.Add(new XElement("Aliases", string.Join(",", aliases)));
                references.Add(reference);
            }
            if (references.HasElements) project.Add(references);
            AddItems(project, "Analyzer", assembly.Analyzers);
            AddItems(project, "AdditionalFiles", assembly.AdditionalFiles);
            AddItems(project, "GlobalAnalyzerConfigFiles", new[] { assembly.AnalyzerConfig });
            project.Add(new XElement("Import", new XAttribute("Project", "Sdk.targets"), new XAttribute("Sdk", "Microsoft.NET.Sdk")));
            return project.ToString().Replace("\r\n", "\n") + "\n";
        }

        private static void AddProperty(XElement properties, string name, string value)
        {
            if (!string.IsNullOrEmpty(value)) properties.Add(new XElement(name, value));
        }

        private static void AddItems(XElement project, string name, IEnumerable<string> values)
        {
            var items = new XElement("ItemGroup", Sorted(values).Select(value => new XElement(name, new XAttribute("Include", MsBuildLiteral(value)))));
            if (items.HasElements) project.Add(items);
        }

        private static IEnumerable<string> Sorted(IEnumerable<string> values) => values
            .Where(v => !string.IsNullOrWhiteSpace(v)).Distinct(StringComparer.Ordinal).OrderBy(v => v, StringComparer.Ordinal);

        private static string MsBuildLiteral(string value)
        {
            foreach (var character in new[] { '%', '$', '@', '\'', ';', '?', '*' })
                value = value.Replace(character.ToString(), "%" + ((int)character).ToString("X2"));
            return value;
        }

        private static string GuidFor(string name)
        {
            using (var md5 = MD5.Create())
                return new Guid(md5.ComputeHash(Utf8.GetBytes("com.hacbit.ide.openidea:" + name))).ToString("D").ToUpperInvariant();
        }

        private static string SolutionText(ProjectAssembly[] assemblies)
        {
            var text = new StringBuilder("Microsoft Visual Studio Solution File, Format Version 12.00\r\n# Visual Studio Version 17\r\n");
            foreach (var assembly in assemblies)
                text.Append("Project(\"{").Append(ProjectTypeGuid).Append("}\") = \"").Append(assembly.Name)
                    .Append("\", \"").Append(assembly.Name).Append(".csproj\", \"{").Append(GuidFor(assembly.Name)).Append("}\"\r\nEndProject\r\n");
            text.Append("Global\r\n\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\r\n\t\tDebug|Any CPU = Debug|Any CPU\r\n\t\tRelease|Any CPU = Release|Any CPU\r\n\tEndGlobalSection\r\n\tGlobalSection(ProjectConfigurationPlatforms) = postSolution\r\n");
            foreach (var assembly in assemblies)
                foreach (var configuration in new[] { "Debug", "Release" })
                {
                    var entry = "\t\t{" + GuidFor(assembly.Name) + "}." + configuration + "|Any CPU";
                    text.Append(entry).Append(".ActiveCfg = ").Append(configuration).Append("|Any CPU\r\n");
                    text.Append(entry).Append(".Build.0 = ").Append(configuration).Append("|Any CPU\r\n");
                }
            return text.Append("\tEndGlobalSection\r\nEndGlobal\r\n").ToString();
        }

        private static void ValidateName(string name)
        {
            if (string.IsNullOrWhiteSpace(name) || name.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || name.IndexOfAny(new[] { '/', '\\', '"', '\r', '\n' }) >= 0)
                throw new InvalidDataException("Invalid assembly name: " + name);
        }

        private static bool WriteIfChanged(string path, string content)
        {
            if (File.Exists(path) && File.ReadAllText(path) == content) return false;
            var temporary = path + ".openidea-" + Guid.NewGuid().ToString("N") + ".tmp";
            try
            {
                File.WriteAllText(temporary, content, Utf8);
                if (File.Exists(path)) File.Replace(temporary, path, null, true);
                else File.Move(temporary, path);
                return true;
            }
            finally
            {
                if (File.Exists(temporary)) File.Delete(temporary);
            }
        }
    }
}
